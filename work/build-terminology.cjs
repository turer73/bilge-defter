'use strict';
// Generates the Wikidata-derived block of terminology-data.js from pinned inputs in
// work/terminology/. The hand-written 100-concept pilot above the block is never changed.
//   node work/build-terminology.cjs candidates  -> review candidates recomputed from the snapshot
//   node work/build-terminology.cjs terms       -> terminology/library-terms.json for the page count
//   node work/build-terminology.cjs             -> verify every input and rewrite the block
//   node work/build-terminology.cjs check       -> verify, and fail unless the block is already current
const fs=require('fs'),path=require('path'),crypto=require('crypto'),assert=require('node:assert/strict');
const dir=path.join(__dirname,'terminology'),target=path.join(__dirname,'bilge-defter-test/terminology-data.js');
const sha=bytes=>crypto.createHash('sha256').update(bytes).digest('hex');
const json=name=>JSON.parse(fs.readFileSync(path.join(dir,name),'utf8'));
const BEGIN='  // BEGIN GENERATED by work/build-terminology.cjs — edit work/terminology/, not this block.\n',END='  // END GENERATED\n';
const CATEGORIES=new Set(['organ','sinir','kas','kemik','bölge','damar','bağ','eklem','lenf','duyu','kalp','doku']);
// Same word, different concepts, both kept on purpose and explained in their notes.
const HOMONYMS=new Set(['la:os','la:femur']);
// The search engine's exact key: identical words clash, accent-folded neighbours (kaş/kas) do not.
const exactKey=(s,lang)=>s.normalize('NFC').toLocaleLowerCase(lang==='tr'?'tr-TR':'en-US').trim().replace(/\s+/g,' ');

const v=(b,k)=>b[k]?.value||'';
function snapshot(receiptName){
  const receipt=json(receiptName),bytes=fs.readFileSync(path.join(dir,receipt.file));
  assert.equal(sha(bytes),receipt.sha256,'Wikidata snapshot hash '+receipt.file);
  assert.equal(sha(fs.readFileSync(path.join(dir,receipt.query_file),'utf8').trim()),receipt.query_sha256,'query hash '+receipt.query_file);
  const items=new Map(JSON.parse(bytes).results.bindings.map(b=>{const id=v(b,'item').split('/').pop();return [id,{id,tr:v(b,'TR'),en:v(b,'EN'),la:v(b,'LA'),ta98:v(b,'TA98'),ta2:v(b,'TA2')}]}));
  assert.equal(items.size,receipt.items);
  return {receipt,items};
}
// Turkish-labelled anatomy items (frequency-selected candidates) and chapter A04 muscles (editor-selected).
const {receipt,items}=snapshot('wikidata-receipt.json'),muscles=snapshot('wikidata-muscles-receipt.json');
delete require.cache[require.resolve(target)];
const pilot=require(target).concepts.filter(c=>!c.labelSource);
assert.equal(pilot.length,100,'hand-written pilot');

// Candidate selection, exactly as used to prepare review-v62.txt.
const fold=s=>s.toLocaleLowerCase('tr').normalize('NFKD').replace(/[̀-ͯ]/g,'').replace(/ı/g,'i').replace(/[^a-z0-9]+/g,' ').trim();
const foldEn=s=>fold(s).replace(/\b(muscle|bone|gland)\b/g,'').replace(/\s+/g,' ').trim();
function candidates(){
  const pages=json('candidate-pages.json').pages,exEn=new Map(),exLa=new Map(),exTr=new Map();
  for(const c of pilot){exEn.set(foldEn(c.labels.en),c.id);for(const a of c.aliases.en)exEn.set(foldEn(a),c.id);exLa.set(fold(c.labels.la),c.id);exTr.set(fold(c.labels.tr),c.id);for(const a of c.aliases.tr)exTr.set(fold(a),c.id)}
  return [...items.values()].filter(r=>{
    const total=Object.values(pages[r.id]||{}).reduce((a,x)=>a+x,0);
    const dup=exEn.get(foldEn(r.en))||(r.la&&exLa.get(fold(r.la)))||exTr.get(fold(r.tr));
    return !(dup||total<5||!r.la||/[^\u0000-ɏ\s\-']/.test(r.tr)||/\(|\)/.test(r.tr)||(fold(r.tr)===fold(r.en)&&/\s/.test(r.tr)));
  }).map(r=>r.id);
}

function review(file,source){
  const rows=[];
  for(const line of fs.readFileSync(path.join(dir,file),'utf8').split('\n')){
    if(!line.trim()||line.startsWith('#'))continue;
    const f=line.split('|');assert.equal(f.length,12,line);
    const [qid,decision,slug,category,tr,trAliases,en,enAliases,la,abbr,note,reason]=f.map(s=>s.trim());
    assert.ok(source.has(qid),qid);assert.ok(['A','R'].includes(decision),qid);
    if(decision==='R'){assert.ok(reason,qid+' reject reason');rows.push({qid,decision,reason});continue}
    assert.match(slug,/^[a-z0-9]+(-[a-z0-9]+)*$/,qid);assert.ok(CATEGORIES.has(category),qid+' '+category);
    for(const x of [tr,en,la])assert.ok(x,qid);
    const list=s=>s?s.split(';').map(x=>x.trim()).filter(Boolean):[];
    rows.push({qid,decision,id:'anatomy.'+slug,category,labels:{tr,en,la},aliases:{tr:list(trAliases),en:list(enAliases),la:[]},abbreviations:list(abbr),note,reason});
  }
  return rows;
}

// edited: Wikidata had this label and the editor changed it; added: Wikidata had none.
function concepts(rows,source){
  const same=(a,b,lang)=>a.toLocaleLowerCase(lang).trim()===b.toLocaleLowerCase(lang).trim();
  return rows.filter(r=>r.decision==='A').map(r=>{
    const w=source.get(r.qid),lang=l=>l==='tr'?'tr-TR':'en-US';
    const edited=['tr','en','la'].filter(l=>w[l]&&!same(r.labels[l],w[l],lang(l))),added=['tr','en','la'].filter(l=>!w[l]);
    return {id:r.id,category:r.category,labels:r.labels,aliases:r.aliases,abbreviations:r.abbreviations,note:r.note,reviewStatus:'draft',referenceCandidates:['fipat-ta2'],verifiedSources:[],
      labelSource:{id:'wikidata',item:r.qid,...(w.ta98?{ta98:w.ta98}:{}),...(w.ta2?{ta2:w.ta2}:{}),edited,added}};
  });
}

function checkLabels(all){
  const ids=new Set();for(const c of all){assert.ok(!ids.has(c.id),'duplicate id '+c.id);ids.add(c.id)}
  const seen=new Map(),clashes=[];
  for(const c of all)for(const lang of ['tr','en','la'])for(const t of new Set([c.labels[lang],...(c.aliases[lang]||[])].filter(Boolean).map(x=>lang+':'+exactKey(x,lang)))){
    const owner=seen.get(t);if(owner&&owner!==c.id&&!HOMONYMS.has(t))clashes.push(`${t} ${owner} ${c.id}`);seen.set(t,owner||c.id);
  }
  return clashes;
}

